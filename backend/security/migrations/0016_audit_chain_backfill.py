GENESIS = "0" * 64
DOMAIN = b"HESABDARI-AUDIT-CHAIN-V1\x00"
SCHEMA = "hesabdari.audit-event.v1"


def _normalize(value):
    from datetime import datetime, date
    from decimal import Decimal
    if value is None or isinstance(value, (str, bool, int)):
        return value
    if isinstance(value, float):
        import math
        if not math.isfinite(value):
            raise ValueError("non-finite float in legacy audit row")
        return value
    if isinstance(value, uuid.UUID):
        return str(value).lower()
    if isinstance(value, Decimal):
        if not value.is_finite():
            raise ValueError("non-finite Decimal in legacy audit row")
        return "0" if value == 0 else format(value.normalize(), "f")
    if isinstance(value, datetime):
        if timezone.is_naive(value):
            value = timezone.make_aware(value, dt_timezone.utc)
        return value.astimezone(dt_timezone.utc).isoformat(timespec="microseconds").replace("+00:00", "Z")
    if isinstance(value, date):
        return value.isoformat()
    if isinstance(value, (list, tuple)):
        return [_normalize(item) for item in value]
    if isinstance(value, dict):
        return {key: _normalize(value[key]) for key in sorted(value)}
    raise TypeError(f"unsupported legacy audit value: {type(value).__name__}")


def _payload(row):
    return {
        "schema": SCHEMA,
        "event_uuid": str(row.event_uuid).lower(),
        "user_id": row.user_id,
        "action": row.action,
        "entity": row.entity,
        "entity_id": row.entity_id,
        "reference": row.reference,
        "previous_state": row.previous_state,
        "new_state": row.new_state,
        "reason": row.reason,
        "created_at": row.created_at,
        "actor_snapshot": row.actor_snapshot,
        "authorization_context": row.authorization_context,
        "source_fingerprint": row.source_fingerprint,
    }


def backfill_audit_chain(apps, schema_editor):
    AuditEvent = apps.get_model("security", "AuditEvent")
    AuditChainHead = apps.get_model("security", "AuditChainHead")
    alias = schema_editor.connection.alias
    previous = GENESIS
    last_id = None

    for row in AuditEvent.objects.using(alias).order_by("created_at", "pk").iterator():
        row.event_uuid = uuid.uuid5(
            uuid.NAMESPACE_URL,
            f"hesabdari-audit-legacy-v1:{row.pk}:{row.created_at.isoformat()}",
        )
        # This is an explicit statement of missing historical evidence, not a
        # reconstruction from current role assignments.
        row.actor_snapshot = {
            "actor_type": "LEGACY",
            "user_id": str(row.user_id) if row.user_id is not None else None,
            "roles": [],
            "permission_overrides": [],
            "historical_context": "NOT_RECORDED_AT_ORIGIN",
        }
        row.authorization_context = {
            "capture": "LEGACY_UNAVAILABLE",
            "operation_id": None,
            "permission_key": None,
        }
        row.source_fingerprint = ""
        row.prev_event_hash = previous
        data = json.dumps(
            _normalize(_payload(row)),
            ensure_ascii=False,
            sort_keys=True,
            separators=(",", ":"),
            allow_nan=False,
        ).encode("utf-8")
        row.event_hash = hashlib.sha256(
            DOMAIN + bytes.fromhex(previous) + data
        ).hexdigest()
        row.save(using=alias, update_fields=[
            "event_uuid", "actor_snapshot", "authorization_context",
            "source_fingerprint", "prev_event_hash", "event_hash",
        ])
        previous = row.event_hash
        last_id = row.pk

    AuditChainHead.objects.using(alias).create(
        pk=1,
        head_hash=previous,
        last_event_id=last_id,
    )


def noop_reverse(apps, schema_editor):
    # Chain backfill is intentionally irreversible: dropping hashes would
    # destroy the integrity evidence generated by this migration.
    raise RuntimeError("W0-2E audit-chain backfill is irreversible")


